-- Weekly family meeting: when it happens, and per-meeting picks (value of the week).
create table if not exists public.meeting_settings (
  family_id uuid primary key references public.families(id) on delete cascade,
  day smallint not null default 0 check (day between 0 and 6), -- 0 = Sunday
  time time not null default '19:00',
  duration_min smallint not null default 30 check (duration_min between 10 and 180),
  updated_at timestamptz not null default now()
);
alter table public.meeting_settings enable row level security;
create policy meeting_settings_all on public.meeting_settings for all
  using (public.is_family_member(family_id)) with check (public.is_family_member(family_id));

create table if not exists public.family_meetings (
  family_id uuid not null references public.families(id) on delete cascade,
  meeting_date date not null,
  value_key text not null check (char_length(value_key) <= 40),
  created_at timestamptz not null default now(),
  primary key (family_id, meeting_date)
);
alter table public.family_meetings enable row level security;
create policy family_meetings_all on public.family_meetings for all
  using (public.is_family_member(family_id)) with check (public.is_family_member(family_id));

-- Items generated by the app on a schedule (e.g. 'family_meeting'); one per start time.
alter table public.items add column if not exists series text check (series is null or char_length(series) <= 40);
create unique index if not exists items_series_start on public.items (family_id, series, starts_at) where series is not null;
